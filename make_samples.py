def write_pdf(path):
    # pymupdf 2.1 的 legacy 写入 API（insert_text / 多页 new_page）已损坏，用 Story/DocumentWriter
    arch = pymupdf.Archive()
    arch.add("C:/Windows/Fonts/msyh.ttc", "msyh.ttc")  # 2.1 签名: add(content, name)
    css = (
        "@font-face {font-family: msyh; src: url(msyh.ttc);}"
        "* {font-family: msyh;}"
        "h1 {font-size: 16pt; font-weight: bold; margin: 14pt 0 8pt 0;}"
        "h2 {font-size: 13pt; font-weight: bold; margin: 10pt 0 6pt 0;}"
        "p {font-size: 11pt; line-height: 1.5; margin: 0 0 6pt 0;}"
        "table {border-collapse: collapse; margin: 8pt 0;}"
        "td {border: 0.5pt solid #000; padding: 4pt 6pt; font-size: 10pt;}"
    )
    parts = [f"<h1 style='font-size:20pt;text-align:center'>{PDF_TITLE}</h1>"]
    for kind, text in PDF:
        if kind == "h1":
            parts.append(f"<h1>{text}</h1>")
        elif kind == "h2":
            parts.append(f"<h2>{text}</h2>")
        else:
            parts.append(f"<p>{text}</p>")
            if text.startswith("项目计划分三个阶段"):
                trs = "".join(
                    "<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>"
                    for row in [PDF_TABLE_HEADERS, *PDF_TABLE_ROWS]
                )
                parts.append(f"<table>{trs}</table>")
    html = "".join(parts)
    fd, raw_name = tempfile.mkstemp(prefix="doc2ppt_sample_", suffix=".pdf")
    os.close(fd)
    raw = Path(raw_name)
    writer = pymupdf.DocumentWriter(str(raw))
    story = pymupdf.Story(html=html, user_css=css, archive=arch)
    mediabox = pymupdf.paper_rect("a4")
    where = mediabox + (72, 36, -72, -36)
    more = 1
    while more:
        dev = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    # 嵌入的完整字体文件（msyh.ttc）会让 PDF 膨胀到 ~19MB；子集化只保留用到的
    # 字形，文本层与表格结构不变（实测 18.8MB → 0.25MB，解析结果逐块一致）。
    doc = pymupdf.open(str(raw))
    doc.subset_fonts()
    tmp = path.parent / (path.name + ".tmp")
    doc.save(str(tmp), garbage=4, deflate=True)
    doc.close()
    for attempt in range(10):  # 刚写出的文件可能被杀毒软件短暂占用
        try:
            tmp.replace(path)
            break
        except PermissionError:
            time.sleep(0.5)
    else:
        raise PermissionError(f"无法写入 {path}（文件被其他程序占用）")
    try:
        raw.unlink()
    except OSError:
        pass  # 系统临时目录；Windows 可能短时占用，留给系统清理


