def write_docx(path):
    from docx import Document
    from docx.oxml.ns import qn as dqn
    from docx.shared import Pt as DPt

    def style_run(r, size=11, bold=False):
        r.font.name = "微软雅黑"
        r._element.rPr.rFonts.set(dqn("w:eastAsia"), "微软雅黑")
        r.font.size = DPt(size)
        r.font.bold = bold

    doc = Document()
    style_run(doc.add_heading("", level=0).add_run(DOCX_TITLE), size=16, bold=True)
    for kind, text in DOCX:
        if kind == "table":
            table = doc.add_table(rows=1, cols=len(DOCX_TABLE_HEADERS))
            for j, h in enumerate(DOCX_TABLE_HEADERS):
                cell = table.rows[0].cells[j]
                cell.text = ""
                style_run(cell.paragraphs[0].add_run(h), bold=True)
            for row in DOCX_TABLE_ROWS:
                cells = table.add_row().cells
                for j, v in enumerate(row):
                    cells[j].text = ""
                    style_run(cells[j].paragraphs[0].add_run(v))
            continue
        if kind == "h1":
            style_run(doc.add_heading("", level=1).add_run(text), size=14, bold=True)
        elif kind == "h2":
            style_run(doc.add_heading("", level=2).add_run(text), size=12, bold=True)
        elif kind == "p":
            style_run(doc.add_paragraph().add_run(text))
        elif kind == "bullet":
            style_run(doc.add_paragraph(style="List Bullet").add_run(text))
        elif kind == "num":
            style_run(doc.add_paragraph(style="List Number").add_run(text))
    doc.save(path)


